async function getBlogEntries(): Promise<MetadataRoute.Sitemap> {
  if (!process.env.MONGODB_URI) {
    return [];
  }

  try {
    const { getDbAndBucket } = await import("@/lib/mongodb");
    const { db } = await getDbAndBucket("fs");

    const blogs = await db
      .collection("blogs")
      .find(
        { slug: { $exists: true, $ne: "" } },
        { projection: { slug: 1, updatedAt: 1, publishedAt: 1, createdAt: 1 } }
      )
      .sort({ publishedAt: -1 })
      .toArray();

    return blogs.map((blog) => {
      const lastModified = new Date(
        blog.updatedAt || blog.publishedAt || blog.createdAt || Date.now()
      );

      return {
        url: `${SITE_URL}/blog/${blog.slug}`,
        lastModified,
        changeFrequency: "weekly" as const,
        priority: 0.75,
      };
    });
  } catch (error) {
    console.error("Sitemap: failed to fetch blog URLs", error);
    return [];
  }
}

export default async function sitemap(): Promise<MetadataRoute.Sitemap> {
  // Normalize paths (a missing leading slash produced an invalid URL that Search Console
  // flagged as a sitemap error) and keep the first entry when a path is listed twice.
  const seen = new Set<string>();
  const staticEntries: MetadataRoute.Sitemap = [];
  for (const route of STATIC_ROUTES) {
    const path = route.path && !route.path.startsWith("/") ? `/${route.path}` : route.path;
    if (seen.has(path)) continue;
    seen.add(path);
    staticEntries.push({
      url: `${SITE_URL}${path}`,
      lastModified: route.lastModified || new Date(),
      changeFrequency: route.changeFrequency,
      priority: route.priority,
    });
  }

  const blogEntries = await getBlogEntries();

  const cityEntries: MetadataRoute.Sitemap = locationData.map((loc) => ({
    url: `${SITE_URL}/legal-recovery-by-city/${loc.slug}`,
    lastModified: new Date(),
    changeFrequency: "monthly" as const,
    priority: 0.5,
  }));

  const noticeCityEntries: MetadataRoute.Sitemap = locationData.map((loc) => ({
    url: `${SITE_URL}/legal-notice-services/${loc.slug}`,
    lastModified: new Date(),
    changeFrequency: "monthly" as const,
    priority: 0.55,
  }));

  if (!INDEX_LOCATION_PAGES) {
    return [...staticEntries, ...blogEntries];
  }

  return [...staticEntries, ...blogEntries, ...cityEntries, ...noticeCityEntries];
}

